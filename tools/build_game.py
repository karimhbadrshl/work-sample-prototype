"""Build docs/index.html: the fault-finding game as ONE self-contained page (no server, no CDN script).

Run from the repo root:  python tools/build_game.py
Inlines game/style.css, game/engine.js and game/ui.js, so it also opens by double-click. Re-run after any change under game/.
"""
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[1]
G = REPO / "game"

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Fault-finding prototype</title>
<style>@import url('https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=Rubik:wght@400;500&display=swap');</style>
<style>
__CSS__
</style>
</head>
<body>
<div id="app"></div>
<noscript>This prototype needs JavaScript.</noscript>
<!-- Generated by tools/build_game.py from game/. Do not edit by hand. -->
<script>
__ENGINE__
</script>
<script>
__UI__
</script>
</body>
</html>
"""


def main():
    read = lambda n: (G / n).read_text(encoding="utf-8")
    html = (TEMPLATE.replace("__CSS__", read("style.css")).replace("__ENGINE__", read("engine.js").replace("</", "<\\/"))
            .replace("__UI__", read("ui.js").replace("</", "<\\/")))
    out = REPO / "docs/index.html"
    out.parent.mkdir(exist_ok=True)
    (out.parent / ".nojekyll").touch()
    out.write_text(html, encoding="utf-8")
    print(f"Wrote {out.relative_to(REPO)} ({len(html) // 1024} KB)")


if __name__ == "__main__":
    main()
