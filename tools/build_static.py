"""Build docs/index.html: the Streamlit app running in the browser via stlite (Pyodide), no server needed.

Run from the repo root:  python tools/build_static.py
Re-run after changing anything under prototype/ so the published page stays in sync.
"""
import json
import pathlib
import tomllib

REPO = pathlib.Path(__file__).resolve().parents[1]
STLITE = "https://cdn.jsdelivr.net/npm/@stlite/browser@1.9.2/build"   # pinned; bundles Streamlit 1.62
ENTRY = "prototype/app.py"

# Every file the app reads at runtime. Add new data or modules here.
FILES = [
    "prototype/app.py", "prototype/brand.py", "prototype/config.py", "prototype/scorer.py",
    "prototype/APPROACH.md", "prototype/evals/results.md",
    *[str(p.relative_to(REPO)).replace("\\", "/") for p in sorted((REPO / "prototype/data").glob("*.json"))],
]

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Work Sample Prototype</title>
<link rel="stylesheet" href="__STLITE__/stlite.css" />
<style>
  body { margin: 0; background: #F2EFE6; color: #22252B; font-family: Rubik, "Segoe UI", Arial, sans-serif; }
  #loading { padding: 24px 16px; }
</style>
</head>
<body>
<div id="loading">Loading the prototype. The first visit takes about 10 to 30 seconds while it starts in your browser.</div>
<div id="root"></div>
<!-- Generated by tools/build_static.py from the prototype source files. Do not edit by hand. -->
<script id="app-files" type="application/json">__FILES__</script>
<script type="module">
  import { mount } from "__STLITE__/stlite.js";
  const files = JSON.parse(document.getElementById("app-files").textContent);
  mount({ requirements: [], entrypoint: "__ENTRY__", files, streamlitConfig: __CONFIG__ },
        document.getElementById("root"));
  new MutationObserver((_, obs) => {
    if (document.querySelector("#root [data-testid='stApp']")) { document.getElementById("loading").remove(); obs.disconnect(); }
  }).observe(document.getElementById("root"), { childList: true, subtree: true });
</script>
</body>
</html>
"""


def streamlit_config() -> dict:
    """Flatten .streamlit/config.toml into stlite's {"section.key": value} form so local and browser look the same."""
    cfg = tomllib.loads((REPO / ".streamlit/config.toml").read_text(encoding="utf-8"))
    return {f"{sec}.{k}": v for sec, kv in cfg.items() for k, v in kv.items()}


def main():
    files = {f: (REPO / f).read_text(encoding="utf-8") for f in FILES}
    payload = json.dumps(files).replace("</", "<\\/")   # "</" would end the <script> tag early
    html = (TEMPLATE.replace("__STLITE__", STLITE).replace("__ENTRY__", ENTRY)
            .replace("__CONFIG__", json.dumps(streamlit_config())).replace("__FILES__", payload))
    out = REPO / "docs/index.html"
    out.parent.mkdir(exist_ok=True)
    (out.parent / ".nojekyll").touch()
    out.write_text(html, encoding="utf-8")
    print(f"Wrote {out.relative_to(REPO)} ({len(html) // 1024} KB, {len(files)} files)")


if __name__ == "__main__":
    main()
